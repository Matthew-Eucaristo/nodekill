#!/usr/bin/env bash
# Assembles the GitHub Pages site into _site/ (or the directory given).
# Run from the repository root: site/build.sh [outdir]
# The interactive demo on the page is fed by nodekill itself: this script runs
# demo/setup.sh in a throwaway folder (the same generated workspace the GIF is
# recorded on: fake projects, caches, npx entries, global packages and nvm
# versions under a fake HOME, never this machine) and keeps the read-only
# `nodekill scan --json` it makes there as sample.js. Nothing is removed: the
# scan only reads, and the folder is deleted afterwards. The recording is
# converted from demo/demo.gif; without ffmpeg the page falls back to the GIF.
set -euo pipefail
out=${1:-_site}
tmp=$(mktemp -d)
trap 'chmod -R u+w "$tmp" 2>/dev/null; rm -rf "$tmp"' EXIT

rm -rf "$out"
mkdir -p "$out"
cp site/index.html site/style.css site/app.js site/favicon.svg site/og.png \
   site/404.html site/robots.txt site/sitemap.xml "$out"/
cp demo/demo.gif "$out"/demo.gif

# The demo workspace and its scan (demo/setup.sh checks that every reported
# path is inside the fake HOME and that nothing is live).
mkdir "$tmp/demo"
NODEKILL_DEMO_DIR="$tmp/demo" bash demo/setup.sh >/dev/null
# Commands name the stand-in tools by their temp path; keep only the name, as
# the TUI shows them, and refuse to publish anything that still points into
# the build machine.
python3 - "$tmp/demo/scan.json" "$(cd "$tmp/demo" && pwd -P)" "$tmp" "$(uname -s)" >"$out/sample.js" <<'PY'
import json, os, sys
path, demo, tmp, system = sys.argv[1:]
doc = json.load(open(path))
for it in doc["items"]:
    cmd = it.get("command")
    if cmd and cmd[0].startswith(demo + "/bin/"):
        cmd[0] = os.path.basename(cmd[0])
text = json.dumps(doc, ensure_ascii=False, separators=(",", ":"))
for bad in (demo, tmp, os.path.expanduser("~"), "/Users/", "/home/"):
    if bad and bad != "/" and bad in text:
        sys.exit("site build: the demo scan mentions %r; not publishing it" % bad)
if not doc["items"]:
    sys.exit("site build: the demo scan is empty")
os_name = {"Darwin": "macOS", "Linux": "Linux"}.get(system, system)
print("// Generated by site/build.sh: nodekill scan --json on demo/setup.sh's generated workspace. Sample data, not a real machine.")
print("window.NODEKILL_SAMPLE = {\"os\": %s, \"scan\": %s};" % (json.dumps(os_name), text))
PY

# Latest release tag, when tags are available (CI fetches them).
if tag=$(git describe --tags --abbrev=0 2>/dev/null); then
  sed -i.bak "s|<!--version-->[^<]*<!--/version-->|$tag|" "$out/index.html" && rm -f "$out/index.html.bak"
fi

if command -v ffmpeg >/dev/null; then
  ffmpeg -loglevel error -y -i demo/demo.gif -movflags +faststart -pix_fmt yuv420p \
    -vf "scale=trunc(iw/2)*2:trunc(ih/2)*2" -c:v libx264 -crf 24 -preset slow "$out/demo.mp4"
  ffmpeg -loglevel error -y -i demo/demo.gif -vf "select=eq(n\,120)" -frames:v 1 -c:v libwebp -quality 82 "$out/demo-poster.webp" || true
else
  echo "ffmpeg not found: the page will show demo.gif instead of a video" >&2
fi
ls -la "$out"
